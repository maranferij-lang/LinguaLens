// en, uk, de, es — повні й мають однаковий набір ключів (це стереже
// __tests__/i18n.test.js); решта мов падає на англійську.
// Додати мову = скопіювати блок en і перекласти все, нічого не пропускаючи:
// один забутий ключ — і посеред німецького екрана вилазить англійська фраза.
//
// Правила тексту (їх теж перевіряє тест):
// • {n}, {p}, {d}… — підстановки; набір мусить збігатися в усіх мовах.
// • {n|форма|форми|форм} — множина за числом n. Українська має три форми
//   (1 слово, 2 слова, 5 слів), en/de/es — дві (1 word, 2 words). Без цього
//   неминуче виходить «1 слів» чи «1 days» — саме такий текст виглядає дивно.
// • Типографіка: … замість трьох крапок, «» для uk/es, “” для en, „“ для de,
//   апостроф ʼ (uk) і ’ (en, de) — прямі ' і " не використовуємо.
// • Жодних емодзі й галочок у тексті: стримана палітра, іконки малює код.
// • Не пишемо КАПСОМ підписи, які стиль і так переводить у верхній регістр
//   (CAPS, sectionLabel): VoiceOver читає капс по літерах.
//
// v1.3: нові рядки живуть не тут, а у фрагментах src/strings/*.js — по
// одному на потік (shared — W0, core — W1, widgets — W2, onb — W3,
// share — W4, pro — W5), щоб паралельні гілки не правили один файл.
