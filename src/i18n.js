// Індекс форми множини для числа n.
// uk: 0 — «1 слово», 1 — «2 слова», 2 — «5 слів»; en/de/es: 0 — one, 1 — other.
// Intl.PluralRules свідомо не беремо: у Hermes його наявність не гарантована,
// а правила для наших мов уміщаються в кілька рядків.
export function pluralIndex(lang, n) {
  const a = Math.abs(Number(n));
  if (!Number.isFinite(a)) return lang === 'uk' ? 2 : 1;
  if (lang === 'uk') {
    // Дробові («1,5 години») беруть форму «2–4»
    if (!Number.isInteger(a)) return 1;
    const d = a % 10;
    const h = a % 100;
    if (d === 1 && h !== 11) return 0;
    if (d >= 2 && d <= 4 && (h < 12 || h > 14)) return 1;
    return 2;
  }
  return a === 1 ? 0 : 1;
}

// Мова, якою інтерфейс реально говорить: для мов без перекладу UI (fr, pl…)
// це англійська. Дати й підказки мусять іти за нею, а не за «моєю мовою».
export function uiLang(lang) {
  return STRINGS[lang] ? lang : 'en';
}

export function makeT(lang) {
  const code = uiLang(lang);
  const dict = STRINGS[code];
  return (key, vars) => {
    const own = dict[key];
    let s = own ?? STRINGS.en[key] ?? key;
    if (!vars) return s;
    // Правило множини — тієї мови, чий рядок реально взяли: якщо ключа нема
    // в uk і впали на en, то й форми англійські (дві, а не три).
    const rule = own != null ? code : 'en';
    s = s.replace(/\{(\w+)\|([^{}]*)\}/g, (m, k, forms) => {
      if (!(k in vars)) return m;
      const list = forms.split('|');
      return list[Math.min(pluralIndex(rule, vars[k]), list.length - 1)];
    });
    for (const k of Object.keys(vars)) s = s.replaceAll('{' + k + '}', String(vars[k]));
    return s;
  };
}
