// Значення доріжки в мить ms
export function trackAt(track, ms) {
  const k = Array.isArray(track) ? track : TRACKS[track];
  if (!k || !k.length) return 0;
  if (ms <= k[0][0]) return k[0][1];
  for (let i = 1; i < k.length; i++) {
    const [b, vb] = k[i];
    if (ms <= b) {
      const [a, va] = k[i - 1];
      return b === a ? vb : va + ((vb - va) * (ms - a)) / (b - a);
    }
  }
  return k[k.length - 1][1];
}

export function beatAt(ms) {
  let b = 0;
  BEATS.forEach((at, i) => {
    if (ms >= at) b = i;
  });
  return b;
}

// Увесь кадр демо в мить ms: { beat, flash, sweep, outline, peel, dim,
// plate, fly, count, lit, final, … } — по значенню на кожну доріжку.
export function demoAt(ms) {
  const t = Math.max(0, Math.min(END, Number(ms) || 0));
  const out = { beat: beatAt(t) };
  for (const k of Object.keys(TRACKS)) out[k] = trackAt(TRACKS[k], t);
  return out;
}

// Для Animated.interpolate: { inputRange, outputRange } з доріжки
export function rangeOf(track) {
  const k = TRACKS[track];
  return { inputRange: k.map((p) => p[0]), outputRange: k.map((p) => p[1]) };
}

// Дуга польоту наліпки: зсув від чашки до чипа «Мої слова» (лівий верхній
// кут сцени). Квадратична крива Безьє, контрольна точка тягне дугу вгору.
const ARC = [
  { x: 0, y: 0 },
  { x: -30, y: -170 },
  { x: -125, y: -220 },
];
export const FLY_SCALE = 0.18;

export function arcPoint(s) {
  const u = 1 - s;
  return {
    x: u * u * ARC[0].x + 2 * u * s * ARC[1].x + s * s * ARC[2].x,
    y: u * u * ARC[0].y + 2 * u * s * ARC[1].y + s * s * ARC[2].y,
  };
}

// П’ять точок дуги — для interpolate (x і y окремо)
export const FLY_STEPS = [0, 0.25, 0.5, 0.75, 1];
export const FLY_POINTS = FLY_STEPS.map(arcPoint);
